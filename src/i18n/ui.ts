/** "November 6, 2026" / "6 de noviembre de 2026" */
export function longDate(iso: string, lang: Lang) {
  return new Date(iso + 'T12:00:00').toLocaleDateString(lang === 'es' ? 'es-US' : 'en-US', { month: 'long', day: 'numeric', year: 'numeric' });
}

/** "{n} problems" style templates. */
export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
